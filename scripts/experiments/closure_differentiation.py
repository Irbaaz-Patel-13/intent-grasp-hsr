#!/usr/bin/env python
r"""
closure_differentiation.py -- runs grasp_policy over the VLM grid results and
reports how far the inferred constraints differentiate the EXECUTION, not just
the target region.

Consumes files already on the PC:
    vlm_grid_raw.json                (18 cells, contract v1)
    vlm_grid_handover_v2_raw.json    (6 handover cells, contract v2)  [optional]
Emits:
    closure_differentiation.md       table + per-object differentiation counts

No robot, no API calls, no GPU. Run:
    python closure_differentiation.py
"""
import json, os, sys
from collections import defaultdict
from intent_grasp.grasp_policy import closure_policy, explain

# nominal widths ONLY for the illustrative table; at runtime part_width comes
# from the cloud (grasp_close_params.py). Flagged as nominal in the output.
NOMINAL_W = {"mug": 0.080, "bottle": 0.070, "hammer": 0.032,
             "knife": 0.022, "bowl": 0.120, "pan": 0.028}
NOMINAL_PLANE, NOMINAL_TOP = 0.458, 0.530

def load(path):
    if not os.path.exists(path):
        print("  (skip, not found: %s)" % path); return []
    with open(path, encoding="utf-8") as f:
        return json.load(f)

def constraints_of(cell):
    s3 = cell.get("step3") or {}
    c = s3.get("constraints") or {}
    return {"keep_clear": c.get("keep_clear", []) or [],
            "post_grasp_motion": c.get("post_grasp_motion", "translate"),
            "stability_priority": c.get("stability_priority", "med"),
            "thermal_or_hygiene": c.get("thermal_or_hygiene")}, \
           s3.get("target_part", "?")

def rows_from(cells, contract):
    out = []
    for cell in cells:
        obj = cell.get("object", "?"); typ = cell.get("type", "handover")
        con, part = constraints_of(cell)
        w = NOMINAL_W.get(obj)
        p = closure_policy(con, part_width_m=w,
                           plane_z=NOMINAL_PLANE, obj_top_z=NOMINAL_TOP)
        out.append(dict(contract=contract, object=obj, type=typ, part=part,
                        instruction=cell.get("instruction", ""),
                        con=con, p=p))
    return out

def main():
    rows  = rows_from(load("vlm_grid_raw.json"), "v1")
    rows += rows_from(load("vlm_grid_handover_v2_raw.json"), "v2")
    if not rows:
        sys.exit("No grid results found. Run vlm_grid.py first (and optionally "
                 "vlm_grid_handover_v2.py), then re-run this from the same folder.")

    L = ["# Constraint-conditioned closure parameters",
         "",
         "Generated by `closure_differentiation.py` from the saved VLM grid runs.",
         "Region selection (`target_part`) was already instruction-conditioned; this",
         "table shows the **execution** parameters now derived from the same inferred",
         "constraints. Widths are nominal here for illustration -- at runtime",
         "`part_width` comes from the point cloud, so `cage` values are indicative only.",
         "",
         "| contract | object | task | part | stability | motion | thermal | force | effort | hold (rad) | close_z | lift (m) | tilt |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        c, p = r["con"], r["p"]
        L.append("| %s | %s | %s | %s | %s | %s | %s | **%s** | %.2f | %+.3f | %.3f | %.2f | %s |"
                 % (r["contract"], r["object"], r["type"], r["part"],
                    c["stability_priority"], c["post_grasp_motion"],
                    c["thermal_or_hygiene"] or "-", p["force_level"], p["effort"],
                    p["hold_margin_rad"], p.get("close_z", float("nan")),
                    p["lift_m"], "yes" if p["requires_controlled_tilt"] else "-"))

    # differentiation: distinct execution signatures per object (v1 grid only)
    sig = defaultdict(set)
    for r in rows:
        if r["contract"] != "v1":
            continue
        p = r["p"]
        sig[r["object"]].add((p["force_level"], p["close_depth_frac"],
                              p["lift_m"], p["requires_controlled_tilt"]))
    L += ["", "## Execution differentiation per object (contract v1)", "",
          "Distinct closure signatures across the three instruction types.",
          "A count of 1 means the constraints did **not** change the physical action.",
          "", "| object | distinct closure signatures (of 3 tasks) |", "|---|---|"]
    for o in sorted(sig):
        L.append("| %s | %d |" % (o, len(sig[o])))
    tot = sum(len(v) for v in sig.values()); n = len(sig)
    L += ["", "**%d/%d objects show >1 distinct closure signature; mean %.2f of 3.**"
          % (sum(1 for v in sig.values() if len(v) > 1), n, tot / max(n, 1))]

    L += ["", "## Worked justifications", ""]
    for r in rows:
        if r["contract"] == "v1":
            L.append("- **%s / %s** — %s" % (r["object"], r["type"],
                                             explain(r["con"], r["p"])))

    md = "\n".join(L)
    with open("closure_differentiation.md", "w", encoding="utf-8") as f:
        f.write(md + "\n")
    print(md[:1800])
    print("\n[closure] wrote closure_differentiation.md  (%d rows)" % len(rows))

if __name__ == "__main__":
    main()
